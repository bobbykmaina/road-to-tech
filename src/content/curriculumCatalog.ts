function createEntry(
  trackId: ActiveStudyTrackId,
  unitId: string,
  unitNumber: string,
  unitTitle: string,
  topicId: string,
  topicNumber: string,
  topicTitle: string,
  opts: {
    entryId: string;
    contentId: string;
    code: string;
    title: string;
    relation: LessonVersionScope;
    officialTopicIds: string[];
    domainId?: string;
    readMinutes: number;
    prerequisites: string[];
    summary: string;
    available?: boolean;
    verifyFlag?: string;
    versionAddendum?: VersionAddendum;
  },
): TrackLessonEntry {
  return {
    entryId: opts.entryId,
    contentId: opts.contentId,
    trackId,
    moduleId: trackId === 'it-support' ? 'it-support' : 'ccna',
    unitId,
    unitNumber,
    unitTitle,
    topicId,
    topicNumber,
    topicTitle,
    code: opts.code,
    title: opts.title,
    readMinutes: opts.readMinutes,
    prerequisites: opts.prerequisites,
    relation: opts.relation,
    officialTopicIds: opts.officialTopicIds,
    domainId: opts.domainId,
    verifyFlag: opts.verifyFlag,
    summary: opts.summary,
    available: Boolean(opts.available || isDeepLessonBuilt(opts.contentId)),
    versionAddendum: opts.versionAddendum,
  };
}

