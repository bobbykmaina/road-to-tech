export function getUnitsForStudyTrack(trackId: ActiveStudyTrackId): TrackUnitPlan[] {
  if (trackId === 'ccna-v1.1') return CCNA_V11_TRACK_UNITS;
  if (trackId === 'ccna-v2.0') return CCNA_V20_TRACK_UNITS;
  return IT_SUPPORT_TRACK_UNITS;
}

export function getAllEntriesForStudyTrack(trackId: ActiveStudyTrackId): TrackLessonEntry[] {
  return getUnitsForStudyTrack(trackId).flatMap((u) => u.topics.flatMap((t) => t.lessons));
}

export function getCcnaUnitsForVersion(version: CcnaVersionId): TrackUnitPlan[] {
  return version === 'v1.1' ? CCNA_V11_TRACK_UNITS : CCNA_V20_TRACK_UNITS;
}

export function getAllSearchableTrackEntries(): TrackLessonEntry[] {
  return [
    ...getAllEntriesForStudyTrack('ccna-v2.0'),
    ...getAllEntriesForStudyTrack('ccna-v1.1'),
    ...getAllEntriesForStudyTrack('it-support'),
  ];
}
